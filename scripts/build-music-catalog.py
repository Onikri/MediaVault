"""Build the sound director's music catalogue (src/tts/music-catalog.js).

Source: Kevin MacLeod's public catalogue at incompetech.com (pieces.json), all
pieces licensed CC BY 4.0. Download it once into the cache and run:

    python scripts/build-music-catalog.py .codex-local/cache/incompetech-pieces.json

Only metadata is stored in the repository; the reader streams each track from
incompetech.com while it plays. The selection is for music under a voice:
instrumental (no singers), at least 90 seconds, a balanced number of pieces
per mood, the most descriptive first.
"""
import json, re, sys
from pathlib import Path

FEELS = ['Calming', 'Relaxed', 'Mysterious', 'Mystical', 'Somber', 'Dark', 'Eerie', 'Unnerving', 'Suspenseful',
         'Intense', 'Action', 'Aggressive', 'Epic', 'Driving', 'Uplifting', 'Bright', 'Humorous', 'Bouncy', 'Grooving']
PER_FEEL = {'Calming': 22, 'Relaxed': 18, 'Mysterious': 20, 'Mystical': 16, 'Somber': 20, 'Dark': 18, 'Eerie': 14,
            'Unnerving': 10, 'Suspenseful': 16, 'Intense': 14, 'Action': 14, 'Aggressive': 8, 'Epic': 18, 'Driving': 8,
            'Uplifting': 16, 'Bright': 12, 'Humorous': 10, 'Bouncy': 6, 'Grooving': 4}
SINGING = re.compile(r'\b(voice|vocals?|singers?|singing|rap)\b', re.I)


def seconds(value):
    parts = [int(p) for p in str(value or '0').split(':') if p.isdigit()]
    total = 0
    for part in parts:
        total = total * 60 + part
    return total


def short(text, limit=90):
    text = re.sub(r'\s+', ' ', str(text or '')).strip()
    if len(text) <= limit:
        return text
    cut = text[:limit].rsplit(' ', 1)[0]
    return cut.rstrip(',.;:') + '…'


def main(path):
    pieces = json.loads(Path(path).read_text(encoding='utf-8'))
    usable = []
    for piece in pieces:
        feels = [f.strip() for f in str(piece.get('feel') or '').split(',') if f.strip() in FEELS]
        if not feels or not piece.get('filename', '').endswith('.mp3'):
            continue
        if SINGING.search(str(piece.get('instruments') or '')):
            continue
        length = seconds(piece.get('length'))
        if length < 90:
            continue
        usable.append({'title': piece['title'].strip(), 'file': piece['filename'], 'feels': feels, 'bpm': int(piece.get('bpm') or 0),
                       'seconds': length, 'about': short(piece.get('description')), 'instruments': short(piece.get('instruments'), 60)})
    usable.sort(key=lambda p: (-len(p['about']), p['title']))
    chosen, seen = [], set()
    for feel in FEELS:
        taken = 0
        for piece in usable:
            if taken >= PER_FEEL[feel]:
                break
            if piece['feels'][0] != feel or piece['file'] in seen:
                continue
            seen.add(piece['file'])
            chosen.append(piece)
            taken += 1
    chosen.sort(key=lambda p: (FEELS.index(p['feels'][0]), p['title']))
    rows = [[p['title'], p['file'], p['feels'], p['bpm'], p['seconds'], p['instruments'], p['about']] for p in chosen]
    out = Path(__file__).resolve().parents[1] / 'src' / 'tts' / 'music-catalog.js'
    out.write_text('// Generated by scripts/build-music-catalog.py from incompetech.com pieces.json.\n'
                   '// Music by Kevin MacLeod (incompetech.com), licensed CC BY 4.0. Metadata only:\n'
                   '// the reader streams a track from incompetech.com while it plays.\n'
                   '// [title, file, feels, bpm, seconds, instruments, description]\n'
                   'export const MUSIC=' + json.dumps(rows, ensure_ascii=False, separators=(',', ':')).replace('],[', '],\n[') + ';\n',
                   encoding='utf-8')
    print(len(rows), 'pieces ->', out)


if __name__ == '__main__':
    main(sys.argv[1])
